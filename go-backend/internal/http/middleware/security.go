package middleware

import (
	"net/http"
	"strings"
)

// SecurityHeaders adds conservative browser hardening to panel responses.
func SecurityHeaders(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		h := w.Header()
		h.Set("X-Content-Type-Options", "nosniff")
		h.Set("X-Frame-Options", "DENY")
		h.Set("Referrer-Policy", "no-referrer")
		h.Set("Permissions-Policy", "camera=(), microphone=(), geolocation=()")
		next.ServeHTTP(w, r)
	})
}

// LimitAPIBody keeps JSON API requests bounded while leaving installer and
// websocket routes alone. Backups get a larger ceiling.
func LimitAPIBody(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.HasPrefix(r.URL.Path, "/api/") && r.Body != nil {
			limit := int64(10 << 20)
			if strings.HasPrefix(r.URL.Path, "/api/v1/backup/import") {
				limit = 64 << 20
			}
			r.Body = http.MaxBytesReader(w, r.Body, limit)
		}
		next.ServeHTTP(w, r)
	})
}
